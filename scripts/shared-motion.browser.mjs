async page=>{
 const checks=[];const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 await page.goto('http://127.0.0.1:4173/');
 await page.emulateMedia({reducedMotion:'no-preference'});
 const firstAnimated=await page.evaluate(async()=>{
  window.sharedMotion=await import('/src/ui-motion.js');
  document.body.innerHTML='<div id="motion-fixture" data-theme="dark"><input id="keyboard"><div data-motion-list="test"><article data-motion="item" data-motion-key="one">第一項</article></div><button id="busy">儲存資料</button><button data-tooltip="提示文字" id="tip">提示</button></div>';
  window.stopSharedMotion=window.sharedMotion.initUIMotion(document.querySelector('#motion-fixture'));
  return document.querySelector('[data-motion="item"]').getAnimations().length>0;
 });
 check(firstAnimated,'First item animates');
 await page.waitForTimeout(400);
 const before=await page.locator('#busy').evaluate(n=>n.getBoundingClientRect().width);
 await page.evaluate(()=>{const b=document.querySelector('#busy');sharedMotion.setMotionBusy(b,true);b.textContent='…';});
 check(await page.locator('#busy').evaluate(n=>n.getBoundingClientRect().width)>=before,'Busy label preserves button width');
 await page.evaluate(()=>sharedMotion.setMotionBusy(document.querySelector('#busy'),false));
 check(await page.locator('#busy').getAttribute('aria-busy')===null,'Busy cleanup restores aria state');
 await page.evaluate(()=>{const button=document.querySelector('#busy');button.disabled=true;button.setAttribute('aria-busy','true');});
 await page.waitForTimeout(20);
 await page.evaluate(()=>{const button=document.querySelector('#busy');button.disabled=false;button.removeAttribute('aria-busy');});
 await page.waitForTimeout(20);
 check(await page.locator('#busy').getAttribute('aria-busy')===null,'Observer does not restore handler-owned stale busy state');
 await page.evaluate(()=>{const label=document.createElement('label');label.textContent='密碼';const input=document.createElement('input');input.type='password';input.id='motion-password';label.append(input);document.querySelector('#motion-fixture').append(label);});
 await page.locator('.password-visibility').waitFor();
 await page.locator('.password-visibility').click();
 check(await page.locator('#motion-password').getAttribute('type')==='text','Password visibility toggle works');
 await page.locator('.password-visibility').click();
 check(await page.locator('#motion-password').getAttribute('type')==='password','Password visibility restores masking');
 await page.locator('#keyboard').focus();
 await page.evaluate(()=>{document.querySelector('[data-motion-list]').innerHTML='<article data-motion="item" data-motion-key="one">第一項</article>';});
 await page.waitForTimeout(25);
 check(await page.locator('[data-motion="item"]').evaluate(n=>n.getAnimations().length)===0,'Poll replacement does not replay identical keyed item');
 check(await page.locator('#keyboard').evaluate(n=>n===document.activeElement),'Motion preserves keyboard focus');
 await page.evaluate(()=>{const n=document.querySelector('[data-motion="item"]');window.removing=sharedMotion.motionRemove(n);n.getAnimations()[0]?.pause();});
 check(await page.locator('[data-motion="item"]').count()===1,'Exit retains element during animation');
 check(await page.locator('[data-motion="item"]').evaluate(n=>{const animation=n.getAnimations()[0];animation.currentTime=65;const opacity=Number(getComputedStyle(n).opacity);animation.play();return opacity>0&&opacity<1;}),'Exit fades over time');
 await page.evaluate(()=>window.removing);
 check(await page.locator('[data-motion="item"]').count()===0,'Exit removes element after animation');
 await page.evaluate(()=>{const n=document.createElement('p');n.id='cancel-motion';n.textContent='取消';document.querySelector('#motion-fixture').append(n);window.cancelMotion=sharedMotion.motionRemove(n);sharedMotion.motionEnter(n);});
 await page.waitForTimeout(300);
 check(await page.locator('#cancel-motion').count()===1,'New entrance cancels pending removal');
 await page.locator('#tip').focus();
 check(await page.locator('#tip').evaluate(n=>getComputedStyle(n,'::after').content.includes('提示文字')),'Tooltip supports keyboard focus');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.evaluate(()=>sharedMotion.motionEnter(document.querySelector('#busy')));
 check(await page.locator('#busy').evaluate(n=>n.getAnimations().length)===0,'Reduced motion skips animation');
 await page.evaluate(()=>sharedMotion.motionRemove(document.querySelector('#cancel-motion')));
 check(await page.locator('#cancel-motion').count()===0,'Reduced motion removes immediately');
 await page.setViewportSize({width:320,height:700});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile has no horizontal overflow');
 await page.evaluate(()=>stopSharedMotion());
 return {passed:checks.length,checks};
}
