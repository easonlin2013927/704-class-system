import assert from 'node:assert/strict';
import {cloud} from './cloud.js';
const started=[],pending=[];
const defer=name=>{started.push(name);return new Promise(resolve=>pending.push(()=>resolve(name)));};
cloud.school=name=>defer(name);
cloud.list=()=>defer('announcements');
cloud.countdowns=()=>defer('countdowns');
const loading=cloud.loginData({});
assert.deepEqual(started,['permissions','preferences','mailboxes','announcements','countdowns']);
pending.splice(0).forEach(resolve=>resolve());
assert.equal((await loading).announcements,'announcements');
started.length=0;
const restricted=cloud.loginData({must_change_password:true});
assert.deepEqual(started,['permissions','preferences']);
pending.splice(0).forEach(resolve=>resolve());
const result=await restricted;
assert.equal(result.mailboxes,null);
assert.deepEqual(result.announcements,[]);
assert.deepEqual(result.countdowns,[]);
console.log('Concurrent login loading and restricted-account checks passed');
