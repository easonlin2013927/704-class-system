import assert from 'node:assert/strict';
import {cloud} from './cloud.js';
const started=[],pending=[];
const defer=name=>{started.push(name);return new Promise(resolve=>pending.push(()=>resolve(name)));};
cloud.school=name=>defer(name);
cloud.list=()=>defer('announcements');
cloud.countdowns=()=>defer('countdowns');
let accessShown=false,finished=false;
const loading=cloud.loginData({},()=>{accessShown=true;});
loading.then(()=>{finished=true;});
assert.deepEqual(started,['permissions','preferences','mailboxes','announcements','countdowns']);
pending.shift()();
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(accessShown,true);
assert.equal(finished,false,'Access must render before optional data completes');
pending.splice(0).forEach(resolve=>resolve());
assert.equal((await loading).announcements,'announcements');
started.length=0;
const restricted=cloud.loginData({must_change_password:true});
assert.deepEqual(started,['permissions','preferences']);
pending.splice(0).forEach(resolve=>resolve());
const result=await restricted;
assert.equal(result.mailboxes,null);
assert.deepEqual(result.announcements,[]);
assert.deepEqual(result.countdowns,[]);
let resolveAccess,accessReady=false,loadError;
cloud.school=name=>name==='permissions'?new Promise(resolve=>{resolveAccess=resolve;}):Promise.resolve(null);
cloud.list=async()=>{throw Error('Announcement service unavailable');};
cloud.countdowns=async()=>[];
const failed=cloud.loginData({},()=>{accessReady=true;}).catch(error=>{loadError=error;});
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(loadError,undefined,'Optional data failure must not finish startup before session access is ready');
resolveAccess({permissions:{}});
await failed;
assert.equal(accessReady,true);
assert.equal(loadError.message,'Announcement service unavailable');
console.log('Concurrent login loading and restricted-account checks passed');
